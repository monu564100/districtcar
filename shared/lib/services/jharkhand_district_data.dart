  /// Search across all Jharkhand districts and villages locally
  static List<LocationSearchResult> searchInJharkhand(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return [];

    final List<LocationSearchResult> matched = [];
    districtLocations.forEach((district, list) {
      if (district.toLowerCase().contains(clean)) {
        matched.addAll(list);
      } else {
        for (var loc in list) {
          if (loc.title.toLowerCase().contains(clean) ||
              loc.subtitle.toLowerCase().contains(clean)) {
            matched.add(loc);
          }
        }
      }
    });

    matched.sort((a, b) {
      final aIsKhunti = a.subtitle.toLowerCase().contains('khunti') || a.title.toLowerCase().contains('khunti');
      final bIsKhunti = b.subtitle.toLowerCase().contains('khunti') || b.title.toLowerCase().contains('khunti');
      if (aIsKhunti && !bIsKhunti) return -1;
      if (!aIsKhunti && bIsKhunti) return 1;
      return 0;
    });

    return matched;
  }
